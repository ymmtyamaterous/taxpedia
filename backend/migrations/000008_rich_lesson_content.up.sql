## 🗾 ふるさと納税とは？

応援したい自治体に**「寄付」**をすることで、所得税・住民税の控除が受けられる制度です。名前に「納税」とありますが実際には「**寄付**」です。

> 💡 **シンプルに言うと**
>
> **自己負担2,000円**で、全国の特産品・返礼品がもらえる制度です！

## 💰 控除シミュレーション

| 寄付額 | 自己負担 | 控除される額 |
|--------|---------|------------|
| 10,000円 | 2,000円 | 8,000円 |
| 30,000円 | 2,000円 | 28,000円 |
| 50,000円 | 2,000円 | 48,000円 |

寄付した翌年の**住民税が主に減額**される形で戻ってきます。

## ⚠️ 上限額に注意！

控除される上限額は**年収・家族構成によって異なります**。上限を超えた分は税控除を受けられず全額自己負担になります。

必ず「**ふるさと納税シミュレーター**」で上限額を確認してから寄付しましょう。

