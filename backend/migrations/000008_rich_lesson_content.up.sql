## 📈 NISAとは？

NISA（少額投資非課税制度）は、投資で得た**利益が非課税**になる制度です。通常の口座では約 **20.315%** の税金がかかりますが、NISA口座内では一切課税されません。

> 💡 **2024年から「新NISA」に大幅拡充！**
>
> 非課税期間が**無期限**になり、年間・生涯の投資上限も大幅に増加しました。

## 🆕 新NISAの2つの投資枠

| 枠 | 年間上限 | 対象商品 |
|----|---------|---------|
| 📊 つみたて投資枠 | **120万円** | 金融庁認定の投資信託・ETF |
| 💹 成長投資枠 | **240万円** | 上場株式・投資信託・ETFなど |
| **合計** | **360万円** | 生涯上限：**1,800万円** |

## 🔄 旧NISAと新NISAの比較

| 比較項目 | 旧NISA | 新NISA |
|---------|--------|--------|
| 非課税保有期間 | 5〜20年 | **無期限** |
| 年間投資上限 | 120万円 | **360万円** |
| 生涯上限 | 800万円 | **1,800万円** |
| 売却後の枠 | 消える | **復活する** |

## 💡 活用のコツ

- まず**つみたて投資枠**で少額から積み立てスタート
- 「**長期・積立・分散**」が投資の基本
- 投資に慣れてきたら**成長投資枠**も活用

> ✅ **まとめ**
>
> 新NISAは「無期限・大枠・枠の復活」が特徴。**長期・積立・分散**で着実に資産形成しよう！
