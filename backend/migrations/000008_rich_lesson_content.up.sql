## 📊 税金の2つの分類軸

日本の税金は **「国税 vs 地方税」** と **「直接税 vs 間接税」** の2軸で整理できます。

## 🏢 国税・地方税の代表例

| 税金 | 種別 | 誰が納めるか |
|------|------|-------------|
| 所得税 | 🏢 国税 | 個人の所得に課税 |
| 法人税 | 🏢 国税 | 企業の利益に課税 |
| 消費税 | 🏢 国税 | 消費者が負担、事業者が納付 |
| 相続税・贈与税 | 🏢 国税 | 相続・贈与を受けた人 |
| 住民税 | 🏙️ 地方税 | 前年の所得をもとに課税 |
| 固定資産税 | 🏙️ 地方税 | 土地・建物の所有者 |
| 自動車税 | 🏙️ 地方税 | 自動車の所有者 |

## ⚖️ 直接税 vs 間接税

> 💡 **見分け方のポイント**
>
> 「税を**負担する人**」と「税を**納付する人**」が同じなら**直接税**、違えば**間接税**。

- **直接税**：所得税・住民税・法人税・相続税
- **間接税**：消費税・酒税・たばこ税・関税

## 🛒 身近な消費税

買い物のたびに **10%**（食料品等は軽減税率 **8%**）が上乗せされる、最も身近な間接税です。

> ✅ **まとめ**
>
> 税金は国税・地方税、直接税・間接税の組み合わせで理解しよう。日常で最も身近なのは**消費税**です。
