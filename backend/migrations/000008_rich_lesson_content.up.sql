## 🏠 自宅費用の「按分（あんぶん）」

自宅を仕事にも使っている場合、家賃・光熱費の一部を経費にできます。

> 例：仕事部屋が全体の **20%** → 家賃の **20%** が経費に算入可能

## ⚠️ 10万円以上の資産は「減価償却」

パソコンなど10万円以上の資産は1年で全額経費計上できません。**複数年にわたって分割**して経費計上します（定額法・定率法）。

