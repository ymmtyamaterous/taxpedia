## 🏥 社会保険料の4種類

給与から控除される社会保険料には**4種類**あります。すべて会社と従業員が**折半**（半々）で負担します。

| 保険の種類 | 目的 | 従業員の負担率 |
|-----------|------|--------------|
| 🏥 健康保険 | 医療費の自己負担を3割に抑える | 標準報酬月額の約5% |
| 🧓 厚生年金 | 老後の年金受給 | 標準報酬月額の9.15% |
| 👵 介護保険 | 介護サービスの費用負担 | 40歳から徴収 |
| 💼 雇用保険 | 失業給付・育児休業給付 | 給与の0.6%（一般企業） |

> 💡 **労使折半とは？**
>
> 会社員の社会保険料は**従業員と会社が半分ずつ**負担する仕組みです。
>
> 例：厚生年金保険料率18.3% → **従業員9.15%** ＋ 会社9.15%

## 📈 標準報酬月額の仕組み

社会保険料は「**標準報酬月額**」という区分をもとに計算されます。同じ等級内の人は同じ保険料になります。

## 💰 社会保険料の節税効果

社会保険料は**全額が所得控除**の対象です。年末調整・確定申告で自動的に控除されるため、所得税・住民税の節税にもつながります。

> ✅ **まとめ**
>
> - 健康保険・厚生年金・介護保険・雇用保険の4種類
> - 会社と**折半**なので実際の負担は計算額の半分
> - 全額**所得控除**の対象で節税効果もある
