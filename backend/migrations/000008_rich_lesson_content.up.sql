## 🏛️ 税金とは何か？

税金は、私たちの日常生活を支える社会インフラの**源泉**です。道路・学校・病院・警察などの公共サービスは、すべて税金によって支えられています。

> 💡 **考え方のコツ**
>
> 「取られるもの」ではなく「**社会サービスへの会費**」として考えると、税金の意義が明確になります。

## 📌 税金が支えるサービス

| カテゴリ | 具体例 |
|---------|--------|
| 🛣️ インフラ | 道路・橋・港湾・上下水道 |
| 🏫 教育 | 公立学校・図書館・公民館 |
| 🏥 医療・福祉 | 病院・介護施設・生活保護 |
| 🚨 安全 | 警察・消防・自衛隊 |
| 👶 子育て | 保育所・児童手当 |

## 🗾 国税と地方税

日本の税金は**国税**と**地方税**の2種類に分かれます。

### 🏢 国税（国に納める税）

社会保障・外交・防衛など**国全体の政策**に充てられます。

- **所得税**・**法人税**・**消費税**・相続税・贈与税

### 🏙️ 地方税（自治体に納める税）

地域の道路整備・ゴミ収集・学校運営などに使われます。

- **住民税**・固定資産税・自動車税・事業税

> ✅ **このレッスンのポイント**
>
> - 税金は社会の「会費」と捉えよう
> - **国税**（国に納める）と**地方税**（自治体に納める）の2種類がある
> - 私たちが受けているサービスの多くは税金で賄われている
