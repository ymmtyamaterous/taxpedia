## 📅 源泉徴収とは？

給与や報酬を支払う**会社や事業者**が、支払い時に所得税を差し引いて国に代わりに納付する仕組みです。

> 💡 **なぜ会社が代わりに納める？**
>
> 税の徴収漏れを防ぎ、**確実・効率的**に税収を確保するための仕組みです。

