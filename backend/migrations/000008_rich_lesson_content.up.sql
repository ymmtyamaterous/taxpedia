## 🏦 iDeCoとは？

iDeCo（個人型確定拠出年金）は、自分で掛金を**積み立て・運用**し、60歳以降に受け取る私的年金制度です。

## 🎯 3つの税制優遇

### 1️⃣ 積立時：掛金が全額所得控除

毎月の掛金が**全額「小規模企業共済等掛金控除」**として所得控除になります。

> 💡 **節税シミュレーション**
>
> 年収500万円・掛金月2.3万円（年27.6万円）の場合
> → 所得税＋住民税で 年 **約5.5万円** の節税効果！

### 2️⃣ 運用時：運用益が非課税

iDeCo口座内では**投資の運用益に税金がかかりません**（通常は約20.315%課税）。

### 3️⃣ 受取時：大きな控除が使える

- **一時金**で受け取り → 退職所得控除（非常に大きな控除）
- **年金形式**で受け取り → 公的年金等控除

## 📊 掛金の月額上限

| 加入者の種類 | 月額上限 |
|-----------|---------|
