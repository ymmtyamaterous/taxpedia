## ⚖️ 直接税と間接税の違い

最大のポイントは「**担税者（税を負担する人）**」と「**納税者（実際に納める人）**」が同じかどうかです。

| | 担税者 | 納税者 | 代表例 |
|-|--------|--------|--------|
| **直接税** | 本人 | 本人 | 所得税・住民税・法人税 |
| **間接税** | 消費者 | 事業者 | 消費税・酒税・たばこ税 |

> 💡 **消費税の仕組みを例に**
>
> 買い物をした「消費者」が税を**負担**しますが、税務署に実際に**納付**するのは「販売した事業者」です。

## 💪 直接税の特徴

### メリット：累進課税で格差是正

所得が高いほど税率が上がる**累進課税**を採用しやすく、所得格差を縮小する効果があります。

### デメリット：申告が必要

自分で計算・申告が必要なため、手間がかかります。

## ⚠️ 間接税の「逆進性」

間接税は所得に関係なく一定率が課されるため、低所得者ほど収入に占める税負担の割合が**高くなる**という問題があります。これを「**逆進性**」と呼びます。

> ✅ **まとめ**
>
> - **直接税**：担税者＝納税者。累進課税で格差是正に貢献
> - **間接税**：担税者≠納税者。消費税が代表例。逆進性に注意
