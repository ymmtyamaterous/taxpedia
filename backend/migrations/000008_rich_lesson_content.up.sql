## 💴 給与明細の3つのブロック

給与明細は次の**3つのブロック**で構成されています。

| ブロック | 内容 | キーワード |
|--------|------|-----------|
| 💹 支給欄 | 基本給・残業代・各種手当 | 総支給額 |
| 📉 控除欄 | 税金・社会保険料の差引 | 控除合計 |
| 💴 差引支給額 | 実際に銀行に振り込まれる額 | 手取り |

> 💡 **手取りの目安**
>
> 一般的に手取りは総支給額の **75〜85%** 程度です。月給30万円なら手取りは約22〜25万円。

## 🔍 控除欄の内訳

### 📌 所得税（源泉徴収）

会社が毎月概算で差し引き、**12月の年末調整**で過不足を精算します。

### 📌 住民税

**前年の所得**をもとに計算され、6月〜翌年5月の12か月で分割徴収されます。入社1年目は0円のことも。

### 📌 社会保険料

